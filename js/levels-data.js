//   shops       shop ids (shops-data.js) for the map's 'S' doors, left to right
//   buildings   walk-through background buildings: rows top..bottom at
//               columns col..col+width-1; `roof` (6/7/8) and `wall` (2/3,
//               optional `wall2` to alternate) pick the tile art
//   boss        boss settings for a map with a 'B' (and a '[' arena wall):
