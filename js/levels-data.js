//               'boss3', picks art + music), and either fireballIntervalTicks
//               or fireballIntervalMinTicks/MaxTicks, plus fireballOrigins
//               ('center' and/or 'top')
//
// Handy numbers: the heroine jumps ~3 tiles high and clears a 3-tile gap
